-- Works on both PostgreSQL and H2.

CREATE TABLE flags (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flag_key    VARCHAR(100)  NOT NULL UNIQUE,
    name        VARCHAR(255)  NOT NULL,
    description VARCHAR(1000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE
);

-- The expiry job looks flags up by expiry date.
CREATE INDEX idx_flags_expires_at ON flags (expires_at);

CREATE TABLE flag_environments (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flag_id            BIGINT      NOT NULL REFERENCES flags (id) ON DELETE CASCADE,
    environment        VARCHAR(20) NOT NULL,
    enabled            BOOLEAN     NOT NULL,
    rollout_percentage INTEGER     NOT NULL CHECK (rollout_percentage BETWEEN 0 AND 100),
    rules_json         VARCHAR(100000) NOT NULL DEFAULT '[]',
    CONSTRAINT uk_flag_environment UNIQUE (flag_id, environment)
);

CREATE TABLE flag_targeted_users (
    flag_environment_id BIGINT       NOT NULL REFERENCES flag_environments (id) ON DELETE CASCADE,
    user_id             VARCHAR(255) NOT NULL,
    PRIMARY KEY (flag_environment_id, user_id)
);

-- Append-only. No foreign key to flags, so history survives a flag being deleted.
CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flag_key    VARCHAR(100) NOT NULL,
    action      VARCHAR(30)  NOT NULL,
    environment VARCHAR(20),
    actor       VARCHAR(255) NOT NULL,
    before_json VARCHAR(200000),
    after_json  VARCHAR(200000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_audit_logs_flag_key ON audit_logs (flag_key);
